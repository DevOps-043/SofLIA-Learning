import { STUDY_PLANNER_EVENT_COLORS } from './study-planner-calendar.constants'
import type { BuildStudyPlannerCalendarLogicResultParams } from './study-planner-calendar-logic-result.types'
import {
  getEventColor,
  getEventLayoutsForDay,
  getEventPosition,
  getEventsForDay,
} from './study-planner-calendar.utils'

export function buildStudyPlannerCalendarLogicResult(
  params: BuildStudyPlannerCalendarLogicResultParams,
) {
  return {
    currentDate: params.navigation.currentDate,
    setCurrentDate: params.navigation.setCurrentDate,
    view: params.navigation.view,
    setView: params.navigation.setView,
    events: params.events,
    isLoadingEvents: params.isLoadingEvents,
    isRefreshing: params.isRefreshing,
    hoveredRefreshButton: params.hoveredRefreshButton,
    setHoveredRefreshButton: params.setHoveredRefreshButton,
    selectedEvent: params.selectedEvent,
    setSelectedEvent: params.setSelectedEvent,
    isEventModalOpen: params.isEventModalOpen,
    setIsEventModalOpen: params.setIsEventModalOpen,
    isEditMode: params.isEditMode,
    setIsEditMode: params.setIsEditMode,
    isCreatingEvent: params.isCreatingEvent,
    setIsCreatingEvent: params.setIsCreatingEvent,
    isDeletingEvent: params.isDeletingEvent,
    isSaving: params.isSaving,
    isMounted: params.isMounted,
    eventForm: params.eventForm,
    setEventForm: params.setEventForm,
    toast: params.toast,
    setToast: params.setToast,
    confirmDialog: params.confirmDialog,
    eventColors: STUDY_PLANNER_EVENT_COLORS,
    today: params.navigation.today,
    weekDayNames: params.navigation.weekDayNames,
    hours: params.navigation.hours,
    monthDays: params.navigation.monthDays,
    weekDays: params.navigation.weekDays,
    weekRange: params.navigation.weekRange,
    goToPreviousMonth: params.navigation.goToPreviousMonth,
    goToNextMonth: params.navigation.goToNextMonth,
    goToToday: params.navigation.goToToday,
    goToPreviousWeek: params.navigation.goToPreviousWeek,
    goToNextWeek: params.navigation.goToNextWeek,
    goToPreviousDay: params.navigation.goToPreviousDay,
    goToNextDay: params.navigation.goToNextDay,
    handleManualRefresh: params.handleManualRefresh,
    handleEditEvent: params.handleEditEvent,
    handleDeleteEvent: params.handleDeleteEvent,
    handleSaveEvent: params.handleSaveEvent,
    handleCreateEvent: params.handleCreateEvent,
    getEventsForDay: (date: Parameters<typeof getEventsForDay>[1]) =>
      getEventsForDay(params.events, date),
    getEventColor,
    getEventPosition,
    getEventLayoutsForDay: (date: Parameters<typeof getEventLayoutsForDay>[1]) =>
      getEventLayoutsForDay(params.events, date),
  }
}
