/**
 * Notebook Feature Types
 *
 * Defines the domain model for the notebook page, which lists the user's
 * manual lesson notes (user_lesson_notes) as a browsable collection.
 */

export interface NotebookManualNote {
  kind: 'manual_note'
  noteId: string
  title: string
  contentPreview: string
  content: string
  tags: string[]
  sourceType: 'manual' | 'chat' | 'import'
  isAutoGenerated: boolean
  lessonId: string
  lessonTitle: string
  moduleTitle: string
  courseId: string
  courseTitle: string
  organizationId: string | null
  createdAt: string
  updatedAt: string
}

export type NotebookItem = NotebookManualNote

// ---------------------------------------------------------------------------
// API response shapes
// ---------------------------------------------------------------------------

export interface NotebookNotesResponse {
  items: NotebookItem[]
  nextCursor: string | null
  totalCount: number
}

export interface NotebookUpdateNoteInput {
  title: string
  content: string
  tags: string[]
}

export interface NotebookMutationResponse {
  success: boolean
  item?: NotebookManualNote
  error?: string
}

export interface NotebookCourse {
  courseId: string
  courseTitle: string
  courseThumbnail: string | null
  notesCount: number
}

export interface NotebookCoursesResponse {
  courses: NotebookCourse[]
}

// ---------------------------------------------------------------------------
// Query parameters
// ---------------------------------------------------------------------------

export interface NotebookNotesQueryParams {
  courseId?: string
  cursor?: string
  limit?: number
}

// ---------------------------------------------------------------------------
// UI state
// ---------------------------------------------------------------------------

export type NotebookTab = 'all' | 'by_course'

export type NotebookModalMode = 'read' | 'edit'

export interface NotebookModalState {
  isOpen: boolean
  item: NotebookItem | null
  mode: NotebookModalMode
}

// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

export const NOTEBOOK_DEFAULT_PAGE_SIZE = 20
export const NOTEBOOK_MAX_PAGE_SIZE = 50
export const NOTEBOOK_CONTENT_PREVIEW_LENGTH = 180
