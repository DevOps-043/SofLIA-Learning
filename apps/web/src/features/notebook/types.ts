/**
 * Notebook Feature Types
 *
 * Defines the unified domain model for the notebook page, which aggregates
 * manual lesson notes (user_lesson_notes) and SofLIA module summaries
 * (module_learning_summaries) into a single, browsable collection.
 */

// ---------------------------------------------------------------------------
// Discriminated union: each notebook item is either a manual note or a SofLIA
// summary, distinguished by `kind`.
// ---------------------------------------------------------------------------

export type NotebookItemKind = 'manual_note' | 'soflia_summary'

export interface NotebookManualNote {
  kind: 'manual_note'
  noteId: string
  title: string
  contentPreview: string
  content: string
  tags: string[]
  sourceType: 'manual' | 'chat' | 'import'
  isAutoGenerated: boolean
  lessonId: string
  lessonTitle: string
  moduleTitle: string
  courseId: string
  courseTitle: string
  organizationId: string | null
  createdAt: string
  updatedAt: string
}

export interface NotebookSofliaSummary {
  kind: 'soflia_summary'
  summaryId: string
  title: string
  contentPreview: string
  contentHtml: string
  contentMarkdown: string
  status: 'generating' | 'ready' | 'failed'
  version: number
  moduleId: string
  moduleTitle: string
  courseId: string
  courseTitle: string
  organizationId: string | null
  generatedAt: string | null
  createdAt: string
  updatedAt: string
}

export type NotebookItem = NotebookManualNote | NotebookSofliaSummary

// ---------------------------------------------------------------------------
// API response shapes
// ---------------------------------------------------------------------------

export interface NotebookNotesResponse {
  items: NotebookItem[]
  nextCursor: string | null
  totalCount: number
}

export interface NotebookCourse {
  courseId: string
  courseTitle: string
  courseThumbnail: string | null
  notesCount: number
  summariesCount: number
}

export interface NotebookCoursesResponse {
  courses: NotebookCourse[]
}

// ---------------------------------------------------------------------------
// Query parameters
// ---------------------------------------------------------------------------

export interface NotebookNotesQueryParams {
  courseId?: string
  cursor?: string
  limit?: number
}

// ---------------------------------------------------------------------------
// UI state
// ---------------------------------------------------------------------------

export type NotebookTab = 'all' | 'by_course'

export type NotebookModalMode = 'read' | 'edit'

export interface NotebookModalState {
  isOpen: boolean
  item: NotebookItem | null
  mode: NotebookModalMode
}

// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

export const NOTEBOOK_DEFAULT_PAGE_SIZE = 20
export const NOTEBOOK_MAX_PAGE_SIZE = 50
export const NOTEBOOK_CONTENT_PREVIEW_LENGTH = 180
